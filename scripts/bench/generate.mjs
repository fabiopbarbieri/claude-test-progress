function parseArgs(argv) {
  const options = {
    out: null, scale: 1, seed: 1, fail: false, only: MODULE_IDS.slice(), plugin: null,
    platform: process.platform === 'win32' ? 'win32' : 'posix'
  };
  const needsValue = new Set(['--out', '--scale', '--seed', '--only', '--plugin', '--platform']);
  for (let index = 0; index < argv.length; index++) {
    let name = argv[index];
    let value = null;
    const equals = name.indexOf('=');
    if (name.startsWith('--') && equals > 0) {
      value = name.slice(equals + 1);
      name = name.slice(0, equals);
    }
    if (name === '--fail') {
      if (value !== null) throw new UsageError('--fail takes no value');
      options.fail = true;
      continue;
    }
    if (!needsValue.has(name)) throw new UsageError('Unknown argument: ' + argv[index]);
    if (value === null) {
      index += 1;
      if (index >= argv.length || argv[index].startsWith('--')) throw new UsageError(name + ' needs a value');
      value = argv[index];
    }
    if (name === '--out') options.out = value;
    else if (name === '--scale') {
      options.scale = Number(value);
      if (!/^\d+(\.\d+)?$/.test(value) || !(options.scale > 0) || options.scale > 100) {
        throw new UsageError('--scale must be a number in (0, 100]');
      }
    } else if (name === '--seed') {
      options.seed = Number(value);
      if (!/^-?\d+$/.test(value) || !Number.isSafeInteger(options.seed)) throw new UsageError('--seed must be an integer');
    } else if (name === '--only') {
      const ids = value.split(',').map(id => id.trim());
      const unknown = ids.filter(id => !MODULE_IDS.includes(id));
      if (unknown.length || !ids.length) throw new UsageError('--only needs ids from: ' + MODULE_IDS.join(','));
      options.only = MODULE_IDS.filter(id => ids.includes(id));
    } else if (name === '--plugin') {
      if (!path.isAbsolute(value) && !path.win32.isAbsolute(value)) throw new UsageError('--plugin must be an absolute path');
      // A trailing separator would double up in the joined adapter paths.
      options.plugin = /^([A-Za-z]:)?[\\/]$/.test(value) ? value : value.replace(/[\\/]+$/, '');
    } else if (name === '--platform') {
      if (value !== 'win32' && value !== 'posix') throw new UsageError('--platform must be win32 or posix');
      options.platform = value;
    }
  }
  if (options.out === null || options.out === '') throw new UsageError('--out is required');
  options.out = path.resolve(options.out);
  return options;
}

