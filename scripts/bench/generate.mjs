const JAVA_TYPE = { int: 'int', ints: 'int[]', str: 'String', long: 'long', bool: 'boolean' };
const javaArg = (type, value) => type === 'ints' ? 'new int[] {' + value.join(', ') + '}' :
  type === 'str' ? double(value) : String(value);
const javaExpected = (ret, value) => ret === 'str' ? double(value) : ret === 'long' ? value + 'L' : String(value);

function javaAssert(op, args, expected) {
  const call = 'Ops.' + op.name + '(' + args.map((arg, index) => javaArg(op.params[index], arg)).join(', ') + ')';
  if (op.ret === 'bool') return (expected ? 'assertTrue(' : 'assertFalse(') + call + ');';
  return 'assertEquals(' + javaExpected(op.ret, expected) + ', ' + call + ');';
}

function javaMethod(unit, seq) {
  const lines = [];
  if (unit.type === 'single') {
    const slot = unit.slots[0];
    const op = slot.op;
    const body = [];
    if (slot.sleep) body.push('Thread.sleep(' + slot.sleep + ');');
    const asserts = slot.checks.map((check, index) =>
      javaAssert(op, check.args, index === 0 && slot.fail ? wrong(op.ret, check.expected) : check.expected));
    if (slot.reps) {
      body.push('for (int i = 0; i < ' + slot.reps + '; i++) {');
      for (const line of asserts) body.push('  ' + line);
      body.push('}');
    } else body.push(...asserts);
    lines.push('  @Test');
    if (slot.skip) lines.push('  @Disabled("blocked by an upstream fix")');
    lines.push('  void ' + op.name + 'Case' + seq + '()' + (slot.sleep ? ' throws InterruptedException' : '') + ' {');
    for (const line of body) lines.push('    ' + line);
    lines.push('  }');
    return lines;
  }
  const op = unit.op;
  const rows = unit.slots.map(slot => {
    const check = slot.checks[0];
    const expected = slot.fail ? wrong(op.ret, check.expected) : check.expected;
    const cells = check.args.map(String).concat([String(expected)]);
    return '    "' + cells.map(safe).join('|') + '"';
  });
  const names = op.names.map((name, index) => JAVA_TYPE[op.params[index]] + ' ' + name);
  names.push(JAVA_TYPE[op.ret] + ' expected');
  const call = 'Ops.' + op.name + '(' + op.names.join(', ') + ')';
  lines.push('  @ParameterizedTest');
  lines.push("  @CsvSource(delimiter = '|', value = {");
  lines.push(rows.join(',\n'));
  lines.push('  })');
  lines.push('  void ' + op.name + 'Case' + seq + '(' + names.join(', ') + ') {');
  lines.push('    assertEquals(expected, ' + call + ');');
  lines.push('  }');
  return lines;
}

