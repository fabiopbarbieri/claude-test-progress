function planAngular(id, spec, options) {
  const rng = streamFor(options.seed, id);
  const count = scaled(spec.files, options.scale);
  const width = widthFor(count);
  const bedCount = Math.round(count * spec.testbed);
  const bedFiles = new Set(rng.shuffle(Array.from({ length: count }, (_, index) => index)).slice(0, bedCount));
  const features = [];
  const all = [];
  for (let index = 0; index < count; index++) {
    const nn = pad(index + 1, width);
    const testbed = bedFiles.has(index);
    const feature = featureTests(rng, nn, testbed);
    const perFile = feature.tests.service.length + feature.tests.pipe.length + feature.tests.component.length;
    if (perFile !== spec.perFile) throw new Error('Feature ' + nn + ' has ' + perFile + ' tests, expected ' + spec.perFile);
    features.push({ nn, testbed, feature });
    let number = 1;
    for (const test of feature.tests.service.concat(feature.tests.pipe, feature.tests.component)) {
      test.number = pad(number++, 2);
      test.skippable = true;
      test.skip = false;
      test.fail = false;
      all.push(test);
    }
  }
  const expected = applyMarks(streamFor(options.seed, id + ':marks'), all, spec.skip, options.fail);
  const files = new Map();
  const fixture = path.join(ROOT, 'tests', 'dependencies', 'angular9');
  for (const name of ['package.json', 'package-lock.json']) files.set(name, fs.readFileSync(path.join(fixture, name)));
  const configs = angularConfigs(spec);
  for (const name of Object.keys(configs)) files.set(name, configs[name]);
  files.set('src/app/shared/ops.ts', tsOps());
  for (const item of features) {
    files.set('src/app/gen/feature-' + item.nn + '.ts', featureSource(item.feature, item.nn));
    files.set('src/app/gen/feature-' + item.nn + '.spec.ts', specSource(item.feature, item.nn, item.testbed));
  }
  return { files, owned: ['src/app'], expected, units: count };
}

