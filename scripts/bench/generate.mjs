function collectFiles(directory, prefix, out) {
  let names;
  try {
    names = fs.readdirSync(directory);
  } catch (error) {
    if (error.code === 'ENOENT') return;
    throw error;
  }
  for (const name of names) {
    const full = path.join(directory, name);
    if (fs.lstatSync(full).isDirectory()) collectFiles(full, prefix + name + '/', out);
    else out.push(prefix + name);
  }
}

function pruneEmpty(directory) {
  for (const name of fs.readdirSync(directory)) {
    const full = path.join(directory, name);
    if (!fs.lstatSync(full).isDirectory()) continue;
    pruneEmpty(full);
    if (fs.readdirSync(full).length === 0) fs.rmdirSync(full);
  }
}

function writeIfChanged(file, data) {
  const content = Buffer.isBuffer(data) ? data : Buffer.from(data, 'utf8');
  try {
    if (fs.readFileSync(file).equals(content)) return;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

// Only the generated directories lose stale files; toolchain directories are never listed.
function syncModule(root, plan) {
  fs.mkdirSync(root, { recursive: true });
  for (const owned of plan.owned) {
    const directory = path.join(root, ...owned.split('/'));
    const present = [];
    collectFiles(directory, owned + '/', present);
    for (const relative of present) {
      if (!plan.files.has(relative)) removePath(path.join(root, ...relative.split('/')), { force: true });
    }
    if (fs.existsSync(directory)) pruneEmpty(directory);
  }
  for (const relative of Array.from(plan.files.keys()).sort()) {
    writeIfChanged(path.join(root, ...relative.split('/')), plan.files.get(relative));
  }
}

const jsonText = value => JSON.stringify(value, null, 2) + '\n';
const jsonEscape = value => JSON.stringify(value).slice(1, -1);

function main(argv) {
  let options;
  try {
    options = parseArgs(argv);
  } catch (error) {
    if (!(error instanceof UsageError)) throw error;
    process.stderr.write('generate: ' + error.message + '\n' + USAGE + '\n');
    return 2;
  }
  fs.mkdirSync(options.out, { recursive: true });
  const manifest = {
    schemaVersion: 1, generator: GENERATOR, seed: options.seed, scale: options.scale, fail: options.fail,
    platform: options.platform, modules: {}
  };
  const modules = {};
  for (const id of options.only) {
    const spec = SPECS[id];
    const plan = PLANNERS[spec.kind](id, spec, options);
    syncModule(path.join(options.out, id), plan);
    modules[id] = moduleConfig(id, spec, options);
    manifest.modules[id] = { stack: STACKS[spec.kind], cwd: id, adapter: modules[id].adapter, expected: plan.expected };
    const { total, passed, failed, skipped } = plan.expected;
    process.stdout.write(id + ': ' + total + ' tests (' + plan.units + (spec.kind.startsWith('mvn') ? ' classes' : ' files') +
      '; ' + passed + ' passed, ' + failed + ' failed, ' + skipped + ' skipped)\n');
  }
  const template = jsonText({ schemaVersion: 1, modules });
  writeIfChanged(path.join(options.out, 'manifest.json'), jsonText(manifest));
  writeIfChanged(path.join(options.out, '.claude', 'test-progress.template.json'), template);
  if (options.plugin !== null) {
    const materialized = template.split('{{PLUGIN}}').join(jsonEscape(options.plugin))
      .split('{{OUT}}').join(jsonEscape(options.out));
    writeIfChanged(path.join(options.out, '.claude', 'test-progress.json'), materialized);
  }
  return 0;
}

try {
  process.exitCode = main(process.argv.slice(2));
} catch (error) {
  process.stderr.write('generate: ' + (error && error.stack ? error.stack : error) + '\n');
  process.exitCode = 1;
}
