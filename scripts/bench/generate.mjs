function renderIt(test, indent) {
  const keyword = test.skip ? 'xit' : 'it';
  const title = single(test.title + ' (case ' + test.number + ')');
  const wraps = {
    plain: [keyword + '(' + title + ', () => {', '});'],
    fake: [keyword + '(' + title + ', fakeAsync(() => {', '}));'],
    done: [keyword + '(' + title + ', (done: DoneFn) => {', '});'],
    async: [keyword + '(' + title + ', async(() => {', '}));']
  }[test.wrap];
  return [wraps[0]].concat(test.body(test.fail).map(line => '  ' + line), [wraps[1]]).map(line => indent + line).join('\n');
}

function featureSource(feature, nn) {
  const { Feature, pipeOp, serviceOps } = feature;
  const methods = serviceOps.map(op => {
    const params = op.names.map((name, index) => name + ': ' + TS_TYPE[op.params[index]]).join(', ');
    return '  ' + op.name + '(' + params + '): ' + TS_TYPE[op.ret] + ' {\n' +
      '    return ops.' + op.name + '(' + op.names.join(', ') + ');\n  }';
  });
  return `// ${NOTE}
import { Component, Inject, Injectable, Pipe, PipeTransform } from '@angular/core';

import * as ops from '../shared/ops';

@Injectable()
export class ${Feature}Service {
  private readonly entries: string[] = [];

  add(entry: string): number {
    this.entries.push(ops.slug(entry));
    return this.entries.length;
  }

  list(): string[] {
    return this.entries.slice();
  }

  clear(): void {
    this.entries.length = 0;
  }

  delayed<T>(value: T, ms: number): Promise<T> {
    return new Promise<T>(resolve => setTimeout(() => resolve(value), ms));
  }

${methods.join('\n\n')}
}

@Pipe({ name: 'feature${nn}' })
export class ${Feature}Pipe implements PipeTransform {
  transform(value: string): string {
    return ops.${pipeOp.name}(value);
  }
}

@Component({
  selector: 'app-feature-${nn}',
  template:
    '<h2 class="title">{{ title | feature${nn} }}</h2>' +
    '<ul class="items"><li class="item" *ngFor="let item of items">{{ item | feature${nn} }}</li></ul>' +
    '<button class="bump" (click)="bump()">Count: {{ count }}</button>' +
    '<p class="status">{{ status }}</p>'
})
export class ${Feature}Component {
  title = 'overview';
  items: string[] = [];
  count = 0;
  loaded = false;

  constructor(@Inject(${Feature}Service) readonly service: ${Feature}Service) {}

  get status(): string {
    return this.loaded ? 'ready' : 'loading';
  }

  bump(): void {
    this.count += 1;
  }

  refresh(after?: () => void): void {
    setTimeout(() => {
      this.items = this.service.list();
      this.loaded = true;
      if (after) {
        after();
      }
    }, 25);
  }
}
`;
}

function specSource(feature, nn, testbed) {
  const { Feature } = feature;
  const parts = [];
  const section = (name, tests, before) => {
    const blocks = tests.map(test => renderIt(test, '  '));
    return 'describe(' + single(name) + ', () => {\n' + before + blocks.join('\n\n') + '\n});\n';
  };
  parts.push(section(Feature + 'Service', feature.tests.service,
    '  let service: ' + Feature + 'Service;\n\n  beforeEach(() => {\n    service = new ' + Feature + 'Service();\n  });\n\n'));
  parts.push(section(Feature + 'Pipe', feature.tests.pipe,
    '  const pipe = new ' + Feature + 'Pipe();\n\n'));
  if (testbed) {
    parts.push(section(Feature + 'Component', feature.tests.component,
      '  let fixture: ComponentFixture<' + Feature + 'Component>;\n' +
      '  let component: ' + Feature + 'Component;\n\n' +
      '  beforeEach(async(() => {\n    TestBed.configureTestingModule({\n' +
      '      declarations: [' + Feature + 'Component, ' + Feature + 'Pipe],\n' +
      '      providers: [' + Feature + 'Service]\n    }).compileComponents();\n  }));\n\n' +
      '  beforeEach(() => {\n    fixture = TestBed.createComponent(' + Feature + 'Component);\n' +
      '    component = fixture.componentInstance;\n  });\n\n'));
  }
  const body = parts.join('\n');
  const testing = [];
  if (/\basync\(/.test(body)) testing.push('async');
  if (/ComponentFixture</.test(body)) testing.push('ComponentFixture');
  if (/\bfakeAsync\(/.test(body)) testing.push('fakeAsync');
  if (/\bTestBed\./.test(body)) testing.push('TestBed');
  if (/\btick\(/.test(body)) testing.push('tick');
  const local = [Feature + 'Pipe', Feature + 'Service'];
  if (testbed) local.unshift(Feature + 'Component');
  return `// ${NOTE}
${testing.length ? "import { " + testing.join(', ') + " } from '@angular/core/testing';\n\n" : ''}import { ${local.join(', ')} } from './feature-${nn}';

${body}`;
}

