// A test slot is one counted test (an invocation for parameterized tests).
function makeSlot(rng, op, skippable, work) {
  const checks = [];
  const count = rng.chance(0.3) ? 2 : 1;
  for (let index = 0; index < count; index++) checks.push(checkFor(rng, op));
  const sleep = rng.chance(SLEEP_SHARE) ? rng.range(1, 5) : 0;
  const reps = rng.chance(work.share) ? rng.range(work.low, work.high) : 0;
  return { op, checks, sleep, reps, skippable, skip: false, fail: false };
}

function makeRow(rng, op) {
  return { op, checks: [checkFor(rng, op)], sleep: 0, reps: 0, skippable: false, skip: false, fail: false };
}

// Units group slots: a single test, a parameterized method (rows) or a test class (Python).
function layoutUnits(rng, count, mix) {
  const units = [];
  let remaining = count;
  while (remaining > 0) {
    const roll = rng.next();
    if (remaining >= 3 && roll < mix.cls) {
      const size = Math.min(remaining, rng.range(3, 6));
      const slots = [];
      for (let index = 0; index < size; index++) slots.push(makeSlot(rng, rng.pick(OPS), true, mix.work));
      units.push({ type: 'class', slots, label: rng.pick(DOMAINS) });
      remaining -= size;
    } else if (remaining >= 3 && roll < mix.cls + mix.params) {
      const size = Math.min(remaining, rng.range(3, 5));
      const op = rng.pick(SCALAR_OPS);
      const slots = [];
      for (let index = 0; index < size; index++) slots.push(makeRow(rng, op));
      units.push({ type: 'params', op, slots });
      remaining -= size;
    } else {
      units.push({ type: 'single', slots: [makeSlot(rng, rng.pick(OPS), true, mix.work)] });
      remaining -= 1;
    }
  }
  return units;
}

function applyMarks(rng, slots, skipShare, wantFail) {
  const order = rng.shuffle(slots);
  const skippable = order.filter(slot => slot.skippable);
  const skipped = Math.min(Math.round(slots.length * skipShare), skippable.length);
  for (let index = 0; index < skipped; index++) skippable[index].skip = true;
  let failed = 0;
  if (wantFail) {
    const target = Math.max(1, Math.round(slots.length * FAIL_SHARE));
    for (let index = 0; index < order.length && failed < target; index++) {
      if (!order[index].skip) {
        order[index].fail = true;
        failed += 1;
      }
    }
  }
  const total = slots.length;
  return { total, passed: total - skipped - failed, failed, skipped };
}

