function runs(rng) {
  let out = '';
  let last = '';
  const count = rng.range(3, 8);
  for (let index = 0; index < count; index++) {
    let letter = 'abcde'.charAt(rng.int(5));
    if (letter === last) letter = letter === 'e' ? 'a' : String.fromCharCode(letter.charCodeAt(0) + 1);
    out += letter.repeat(rng.range(1, 5));
    last = letter;
  }
  return out;
}

